import mongoose, { Schema, Document } from 'mongoose';
import { CustomerIntakeSubmission, IntakeStatus } from '../../src/types';

export interface CustomerIntakeDocument extends Omit<CustomerIntakeSubmission, 'id'>, Document {
  id: string;
}

const PhotoAttachmentSchema = new Schema(
  {
    name: { type: String, required: true },
    size: { type: String, required: true },
    previewUrl: { type: String }
  },
  { _id: false }
);

const CustomerIntakeSchema = new Schema<CustomerIntakeDocument>(
  {
    id: {
      type: String,
      required: true,
      unique: true,
      index: true,
      trim: true
    },
    submissionNumber: {
      type: String,
      required: true,
      unique: true,
      uppercase: true,
      trim: true,
      index: true
    },
    timestamp: {
      type: String,
      default: () => new Date().toISOString()
    },
    fullName: {
      type: String,
      required: true,
      trim: true
    },
    email: {
      type: String,
      required: true,
      lowercase: true,
      trim: true,
      index: true
    },
    phone: {
      type: String,
      required: true,
      trim: true
    },
    country: {
      type: String,
      required: true,
      trim: true
    },
    preferredContactMethod: {
      type: String,
      enum: ['Email', 'Phone Call', 'WhatsApp'],
      default: 'Email'
    },
    vinOrChassis: {
      type: String,
      required: true,
      uppercase: true,
      trim: true,
      index: true
    },
    registrationPlate: {
      type: String,
      trim: true,
      default: ''
    },
    make: {
      type: String,
      required: true,
      trim: true
    },
    model: {
      type: String,
      required: true,
      trim: true
    },
    modelYear: {
      type: Number,
      required: true
    },
    vehicleColor: {
      type: String,
      default: ''
    },
    currentMileage: {
      type: String,
      default: ''
    },
    countryOfRegistration: {
      type: String,
      required: true
    },
    reportType: {
      type: String,
      required: true
    },
    reasonForRequest: {
      type: String,
      required: true
    },
    purchaseStatus: {
      type: String,
      default: ''
    },
    additionalNotes: {
      type: String,
      default: ''
    },
    documentFileName: {
      type: String
    },
    documentFileSize: {
      type: String
    },
    vehiclePhotos: {
      type: [PhotoAttachmentSchema],
      default: []
    },
    vehiclePhotoCount: {
      type: Number,
      default: 0
    },
    accuracyConfirmed: {
      type: Boolean,
      default: true
    },
    dataUsageConsent: {
      type: Boolean,
      default: true
    },
    termsAgreed: {
      type: Boolean,
      default: true
    },
    status: {
      type: String,
      enum: ['Received', 'Processing', 'Report Generated', 'Delivered', 'Contacted'],
      default: 'Received',
      index: true
    },
    autoGeneratedOrderId: {
      type: String
    },
    autoGeneratedReportUrl: {
      type: String
    },
    internalNotes: {
      type: String,
      default: ''
    }
  },
  {
    timestamps: true,
    toJSON: {
      transform: (_doc, ret: any) => {
        delete ret._id;
        delete ret.__v;
        return ret;
      }
    }
  }
);

CustomerIntakeSchema.index({ email: 1, createdAt: -1 });
CustomerIntakeSchema.index({ vinOrChassis: 1 });

export const CustomerIntakeModel =
  mongoose.models.CustomerIntake ||
  mongoose.model<CustomerIntakeDocument>('CustomerIntake', CustomerIntakeSchema);
